export function getRequestById(id: string) {
  return mockRequests.find((r) => r.id === id);
}

export function getOrderById(id: string) {
  return mockOrders.find((o) => o.id === id);
}

export function getShipmentByOrderId(orderId: string) {
  return mockShipments.find((s) => s.orderId === orderId) ?? mockShipments[0];
}

export function getRequestTimeline(requestId: string): MockShipment['events'] {
  const req = getRequestById(requestId);
  if (!req) return [];
  return [
    {
      id: 't1',
      title: req.status === 'completed' ? 'Completed' : req.explanation,
      description: req.nextStep,
      timestamp: new Date(req.updatedAt).toLocaleString(),
      completed: req.status === 'completed',
      active: req.status !== 'completed' && req.status !== 'cancelled',
    },
    {
      id: 't2',
      title: 'Request received',
      description: 'Logistix received your freight details.',
      timestamp: new Date(req.createdAt).toLocaleString(),
      completed: true,
      active: false,
    },
  ];
}
